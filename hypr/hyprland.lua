-- Load order matters: environment first, then look, then behaviour.
require("modules.environment_variables")
require("modules.monitors")
require("modules.decorations")
require("modules.layout")
require("modules.miscellaneous")
require("modules.input")
require("modules.window_rules")
-- Sleek Shell keybind layer: lets Settings disable/remap/label the binds below without editing them.
local binds_ok, binds_err = pcall(require, "sleekshell.bindlayer")
if not binds_ok and hl.print then hl.print("[sleek-shell] keybind layer disabled: " .. tostring(binds_err)) end
require("modules.keybinds")
require("modules.shell_keys")
pcall(require, "custom_binds")   -- user binds, generated by Sleek Shell Settings > Keyboard
require("modules.autostart")

-- Per-monitor workspaces. The manager seeds itself from the nwg-displays
-- generated workspaces.lua (when that file exists) and then keeps every
-- monitor on its own, independent set of workspaces.
require("modules.workspaces")

-- Your own additions: ~/.config/hypr/user.lua is never shipped, overwritten or removed by the installer.
local user_ok, user_err = pcall(require, "user")
if not user_ok and not tostring(user_err):find("module .user. not found") and hl.print then hl.print("[sleek-shell] user.lua: " .. tostring(user_err)) end
